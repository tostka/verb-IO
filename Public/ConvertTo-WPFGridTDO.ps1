    function Out-WpfGridTDO {
        <#
        .SYNOPSIS
        Out-WpfGridTDO - Jeff Hick's WPF-based out-gridview alternative; doesn't support -passthru (use Read-InputConsoleChoiceTDO if necc)
        .NOTES
