        .DESCRIPTION
        Out-WpfGridTDO - Jeff Hick's WPF-based out-gridview alternative; doesn't support -passthru (use Read-InputConsoleChoiceTDO if necc)
        This is a verb-io-hosted variant; defers to pre-existing copies loaded.
        There is a limitation with autogenerated columns if the property
        contains a period or a slash.

        https://social.msdn.microsoft.com/Forums/sqlserver/en-US/f5f752f6-f08d-4d46-9e1e-78a4496eaf12/why-does-not-datagrid-show-values-if-there-are-a-point-82208221-or-82208221-in-header?forum=wpf

        This command is an alternative to Out-GridView. It works much the same way. Run a PowerShell command and pipe it to this command. The output will be displayed in an auto-sized data grid. You can click on column headings to sort. You can resize columns and you can re-order columns. You will want to be selective about which properties you pipe through to this command. See examples.

        You can specify a timeout value which will automatically close the form. If you specify a timeout and the Refresh parameter, then the contents of the datagrid will automatically refreshed using the timeout value as an integer. This will only work when you pipe a PowerShell expression to Out-WpfGridTDO as one command. This will fail if you break the command in the PowerShell ISE or use a nested prompt. Beginning with v2.4.0 the form now has a Refresh button which will automatically refresh the datagrid. You should set a refresh interval that is greater than the time it takes to complete the command.

        Because the grid is running in a new background runspace, it does not automatically inherit anything from your current session. However, you can use the -UserProfile parameter which will load your user profile scripts into the runspace. You can specify a list of locally defined variables to be used in the form. Use the variable name without the $. Finally, you can also use the -InitializationScript parameter and specify a scriptblock of PowerShell code to initialize the runspace. This is helpful when you need to dot source external scripts or import modules not in your module path.

        This command runs the WPF grid in a new runspace so your PowerShell prompt will not be blocked. However, after closing the form you may be left with the runspace. You can use Remove-Runspace to clean up or wait until you restart PowerShell.

        This command requires a Windows platform.

        .PARAMETER InputObject
        Typically the results of a PowerShell command or expression. You should select the specific properties you wish to display.
        .PARAMETER Scriptblock
        Enter a scriptblock that will generate data to be populated in the form
        .PARAMETER Title
        Specify a title for your form
        .PARAMETER Timeout
        By default, the grid will remain displayed until you manually close it. But you can specify a timeout interval in seconds. The minimum accepted value is 5 seconds. If you use this parameter with -Refresh, then the datagrid will be refreshed with results of the PowerShell expression you piped to Out-WpfGridTDO.
        .PARAMETER Refresh
        If you specify this parameter and a Timeout value, this command will refresh the datagrid with the PowerShell expression piped into Out-WpfGridTDO. You should use a value that is longer than the time it takes to complete the command that generates your data.  This parameter will only work if you are using Out-WpfGridTDO at the end of a pipelined expression. See examples.
        .PARAMETER GridLines
        Gridlines option (All|Horizontal|None|Vertical)
        .PARAMETER InitializationScript
        Run this scriptblock to initialize the background runspace
        .PARAMETER UseLocalVariable
        Load locally defined variables into the background runspace
        .PARAMETER UseProfile
        Load your PowerShell profiles into the background runspace
        .INPUTS
        PSObject    
        .EXAMPLE
        PS> Get-Process | Sort-Object WS -Descending |
        PS>     Select-object -first 20 ID,Name,WS,VM,PM,Handles,StartTime |
        PS>         Out-WpfGridTDO -Refresh -timeout 20 -Title "Top Processes"
        Get the top 20 processes based on the value of the WorkingSet property and display selected properties in the WPF Grid. The contents will automatically refresh every 20 seconds. You will need to manually close the form.
        .EXAMPLE
        PS> $vmhost = "CHI-HVR2"
        PS> Get-VM -computername $VMHost | Select Name,State,Uptime,@{Name="AssignedMB";Expression={$_.MemoryAssigned/1mb -as [int]}},
        PS>     @{Name="DemandMB";Expression={$_.MemoryDemand/1mb -as [int]}} |
        PS>         Out-WpfGridTDO -title "VM Report $VMHost" -timeout 30 -refresh -UseLocalVariable VMHost
        Get Hyper-V virtual machine information and refresh every 30 seconds. Because the command is using a locally defined variable it is also being used in the form. Note that this would be written as one long pipelined expression. It is formatted here for the sake of the help documentation.
        .EXAMPLE
        PS> Get-VMData -host CHI-HVR2 |
        PS>     Out-WpfGridTDO -title "VM Data" -refresh -timeout 60 -UseProfile
        This example uses a hypothetical command that might be defined in a PowerShell profile script. Out-WpfGridTDO will load the profile scripts so that the data can be updated every 60 seconds.
        .EXAMPLE
        PS> (Get-ProcessData -Computername $computers).where({$_.WorkingSet -ge 100mb}) |
        PS>     Out-WpfGridTDO -Title "Process Report" -UseLocalVariable computers -InitializationScript {. C:\scripts\Get-ProcessData.ps1} -Refresh -Timeout 30
        This command runs a function that is defined in a script file. In order for the form to refresh, it must also dot source the script which is happening with the InitializationScript parameter. The example is also loading the local $computers variable so that it too is available upon refresh.
